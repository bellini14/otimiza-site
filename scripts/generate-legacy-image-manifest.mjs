import { createClient } from '@sanity/client'
import { promises as fs } from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'
import { fileURLToPath } from 'node:url'

const DEFAULT_PROJECT_ID = 'igy822g7'
const DEFAULT_DATASET = 'production'
const ASSET_QUERY = '*[_type == "sanity.imageAsset"]{_id, originalFilename, "width": metadata.dimensions.width, "height": metadata.dimensions.height, "url": url}'

export function isSafeLegacyPath(candidate) {
  const prefix = 'wp-content/uploads/'
  if (typeof candidate !== 'string' || !candidate.startsWith(prefix)) return false
  const relativePath = candidate.slice(prefix.length)
  return relativePath.length > 0
    && !relativePath.includes('\\')
    && !relativePath.includes(':')
    && relativePath.split('/').every((segment) => segment !== '' && segment !== '.' && segment !== '..')
}

export function getSanityUrlAssetId(url) {
  if (typeof url !== 'string') return undefined

  try {
    const parsed = new URL(url)
    if (parsed.hostname !== 'cdn.sanity.io') return undefined
    const filename = parsed.pathname.split('/').at(-1)
    return filename && !filename.includes('/') ? filename : undefined
  } catch {
    return undefined
  }
}

function compareByAssetId(left, right) {
  return String(left.assetId ?? '').localeCompare(String(right.assetId ?? ''))
}

function reportAsset(asset, assetId, candidates = []) {
  return {
    assetId,
    sanityId: asset._id,
    originalFilename: asset.originalFilename,
    width: asset.width ?? null,
    height: asset.height ?? null,
    candidates: candidates.map((candidate) => candidate.relativePath).sort(),
  }
}

export function buildLegacyManifest(assets, legacyFiles) {
  const filesByFilename = new Map()
  for (const file of legacyFiles) {
    if (!isSafeLegacyPath(file.relativePath)) continue
    const files = filesByFilename.get(file.filename) ?? []
    files.push(file)
    filesByFilename.set(file.filename, files)
  }

  const entries = []
  const report = { matched: [], missing: [], ambiguous: [], dimensionMismatch: [], invalid: [] }
  for (const asset of assets) {
    const assetId = getSanityUrlAssetId(asset.url)
    if (!assetId || !asset.originalFilename) {
      report.invalid.push(reportAsset(asset, assetId ?? null))
      continue
    }

    const filenameCandidates = filesByFilename.get(asset.originalFilename) ?? []
    const hasDimensions = Number.isFinite(asset.width) && Number.isFinite(asset.height)
    if (!hasDimensions) {
      report.missing.push(reportAsset(asset, assetId, filenameCandidates))
      continue
    }
    const candidates = filenameCandidates.filter((file) => file.width === asset.width && file.height === asset.height)

    if (candidates.length === 1) {
      const entry = { assetId, path: candidates[0].relativePath, sanityId: asset._id }
      entries.push(entry)
      report.matched.push(entry)
    } else if (candidates.length > 1) {
      report.ambiguous.push(reportAsset(asset, assetId, candidates))
    } else if (filenameCandidates.length > 0) {
      report.dimensionMismatch.push(reportAsset(asset, assetId, filenameCandidates))
    } else {
      report.missing.push(reportAsset(asset, assetId))
    }
  }

  entries.sort(compareByAssetId)
  for (const category of Object.values(report)) category.sort(compareByAssetId)

  return {
    manifest: Object.fromEntries(entries.map(({ assetId, path: legacyPath }) => [assetId, legacyPath])),
    report,
  }
}

async function dimensionsForFile(absolutePath) {
  try {
    const metadata = await sharp(absolutePath).metadata()
    return { width: metadata.width, height: metadata.height }
  } catch {
    return { width: undefined, height: undefined }
  }
}

export async function indexLegacyFiles(legacyRoot) {
  const root = path.resolve(legacyRoot)
  const files = []

  async function walk(directory) {
    const entries = await fs.readdir(directory, { withFileTypes: true })
    for (const entry of entries) {
      const absolutePath = path.join(directory, entry.name)
      if (entry.isDirectory()) await walk(absolutePath)
      else if (entry.isFile()) {
        const relative = path.relative(root, absolutePath).split(path.sep).join('/')
        const dimensions = await dimensionsForFile(absolutePath)
        files.push({
          absolutePath,
          relativePath: `wp-content/uploads/${relative}`,
          filename: entry.name,
          ...dimensions,
        })
      }
    }
  }

  await walk(root)
  return files.sort((left, right) => left.relativePath.localeCompare(right.relativePath))
}

export function formatManifest(manifest) {
  return `// Generated by scripts/generate-legacy-image-manifest.mjs. Do not edit manually.\nexport const legacyImageManifest = Object.freeze(${JSON.stringify(manifest, null, 2)})\n`
}

export async function fetchPublicSanityAssets({ projectId = DEFAULT_PROJECT_ID, dataset = DEFAULT_DATASET } = {}) {
  const client = createClient({ projectId, dataset, apiVersion: '2026-08-10', useCdn: true })
  return client.fetch(ASSET_QUERY)
}

function parseArguments(argv) {
  const options = {}
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (!arg.startsWith('--')) throw new Error(`Unknown argument: ${arg}`)
    const value = argv[index + 1]
    if (!value || value.startsWith('--')) throw new Error(`Missing value for ${arg}`)
    options[arg.slice(2)] = value
    index += 1
  }
  return options
}

export async function generateLegacyImageManifest({ legacyRoot, output, reportPath, projectId, dataset }) {
  if (!legacyRoot) throw new Error('--legacy-root <directory> is required')
  const [assets, legacyFiles] = await Promise.all([
    fetchPublicSanityAssets({ projectId, dataset }),
    indexLegacyFiles(legacyRoot),
  ])
  const result = buildLegacyManifest(assets, legacyFiles)
  await fs.mkdir(path.dirname(output), { recursive: true })
  await fs.writeFile(output, formatManifest(result.manifest), 'utf8')
  await fs.mkdir(path.dirname(reportPath), { recursive: true })
  await fs.writeFile(reportPath, `${JSON.stringify(result.report, null, 2)}\n`, 'utf8')
  return { ...result, legacyFiles }
}

async function main() {
  const options = parseArguments(process.argv.slice(2))
  const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
  const output = path.resolve(options.output ?? path.join(repositoryRoot, 'src/data/legacyImageManifest.js'))
  const reportPath = path.resolve(options.report ?? path.join(repositoryRoot, 'scripts/legacy-image-manifest-report.json'))
  const result = await generateLegacyImageManifest({
    legacyRoot: options['legacy-root'],
    output,
    reportPath,
    projectId: options['project-id'],
    dataset: options.dataset,
  })
  console.log(`Mapped ${result.report.matched.length} of ${result.report.matched.length + result.report.missing.length + result.report.ambiguous.length + result.report.dimensionMismatch.length + result.report.invalid.length} assets.`)
  console.log(`Report: ${reportPath}`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message)
    process.exitCode = 1
  })
}
